  const SUPPORTED = Object.keys(TRANSLATIONS);

  function detectLang(stored) {
    if (stored && stored !== 'auto' && TRANSLATIONS[stored]) return stored;
    let nav = 'en';
    try {
      nav = (navigator.language || 'en').replace('-', '_');
    } catch (_) {}
    if (TRANSLATIONS[nav]) return nav;
    const short = nav.slice(0, 2);
    return TRANSLATIONS[short] ? short : 'en';
  }

  function t(key, subs, langOverride) {
    const lang = langOverride || detectLang();
    let text = (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS.en[key] || key;
    if (subs && subs.length) {
      subs.forEach((v, i) => {
        text = text.replace('$' + (i + 1), String(v));
      });
    }
    return text;
  }

